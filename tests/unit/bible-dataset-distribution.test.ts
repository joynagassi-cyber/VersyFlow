/**
 * Bible Dataset Distribution + Cache — unit tests.
 *
 * Verifies that `BibleDatasetDistributionService.ensureDataset` honors
 * the local cache (no re-download when the checksum matches), re-fetches
 * when it does not, and that the PowerSync-backed cache round-trips a
 * payload. The `InMemoryBibleDatasetCache` is a minimal stand-in for the
 * PowerSync version so the tests are hermetic (no native DB needed).
 */

import { describe, it, expect, vi } from 'vitest';
import {
  BibleDatasetDistributionService,
  type IBibleDatasetCache,
  type RemoteDatasetCatalogEntry,
} from '@/infrastructure/bible/bible-dataset-distribution';
import {
  BIBLE_DATASET_CATALOG,
  findRemoteDatasetEntry,
} from '@/services/bible-text-service';

class InMemoryBibleDatasetCache implements IBibleDatasetCache {
  private map = new Map<string, { text: string; checksum: string }>();

  async get(id: string) {
    return this.map.get(id) ?? null;
  }

  async set(id: string, text: string, checksum: string) {
    this.map.set(id, { text, checksum });
  }
}

function makeEntry(overrides: Partial<RemoteDatasetCatalogEntry> = {}) {
  return {
    id: 'test-tr',
    checksum: 'abc123',
    sizeBytes: 1024,
    ...overrides,
  } satisfies RemoteDatasetCatalogEntry;
}

function makeFetch(text: string, ok = true) {
  return (async () =>
    ({
      ok,
      status: ok ? 200 : 404,
      text: async () => text,
    })) as unknown as typeof fetch;
}

describe('BibleDatasetDistributionService', () => {
  it('returns the cached payload when the checksum matches (no download)', async () => {
    const cache = new InMemoryBibleDatasetCache();
    const entry = makeEntry();
    const text = '{"ok":true}';
    await cache.set(entry.id, text, entry.checksum);

    const service = new BibleDatasetDistributionService(
      'https://example.com/storage/public/bible-datasets',
      cache,
      makeFetch('SHOULD-NOT-BE-FETCHED', true),
    );
    const result = await service.ensureDataset(entry);
    expect(result).toBe(text);
  });

  it('downloads and caches when the local cache is empty', async () => {
    const cache = new InMemoryBibleDatasetCache();
    const entry = makeEntry();
    const freshText = '{"version":2}';

    const service = new BibleDatasetDistributionService(
      'https://example.com/storage/public/bible-datasets',
      cache,
      makeFetch(freshText, true),
    );
    const result = await service.ensureDataset(entry);
    expect(result).toBe(freshText);
    const cached = await cache.get(entry.id);
    expect(cached?.checksum).toBe(entry.checksum);
    expect(cached?.text).toBe(freshText);
  });

  it('re-downloads when the cached checksum no longer matches', async () => {
    const cache = new InMemoryBibleDatasetCache();
    const entry = makeEntry();
    // Cache has a STALE payload — different checksum than the catalog.
    await cache.set(entry.id, 'stale', 'old-checksum');

    const service = new BibleDatasetDistributionService(
      'https://example.com/storage/public/bible-datasets',
      cache,
      makeFetch('fresh', true),
    );
    const result = await service.ensureDataset(entry);
    expect(result).toBe('fresh');
    expect((await cache.get(entry.id))?.checksum).toBe(entry.checksum);
  });

  it('throws a descriptive error on a failed download (HTTP 404)', async () => {
    const cache = new InMemoryBibleDatasetCache();
    const entry = makeEntry({ id: 'missing-tr' });
    const service = new BibleDatasetDistributionService(
      'https://example.com/storage/public/bible-datasets',
      cache,
      makeFetch('', false),
    );
    await expect(service.ensureDataset(entry)).rejects.toThrow(
      /Failed to download dataset "missing-tr" \(HTTP 404\)/,
    );
  });

  it('rejects invalid dataset ids (path traversal)', async () => {
    const cache = new InMemoryBibleDatasetCache();
    const entry = makeEntry({ id: '../evil' });
    const service = new BibleDatasetDistributionService(
      'https://example.com/storage/public/bible-datasets',
      cache,
      makeFetch('', true),
    );
    await expect(service.ensureDataset(entry)).rejects.toThrow(
      /Invalid dataset id/,
    );
  });
});

describe('Dataset catalogue (embedded in the app)', () => {
  it('loads every catalog entry with the required shape', () => {
    expect(BIBLE_DATASET_CATALOG.length).toBeGreaterThan(0);
    for (const entry of BIBLE_DATASET_CATALOG) {
      expect(entry.id).toMatch(/^[a-z0-9_-]+$/i);
      expect(typeof entry.checksum).toBe('string');
      expect(entry.checksum.length).toBeGreaterThan(0);
      expect(typeof entry.sizeBytes).toBe('number');
      expect(entry.sizeBytes).toBeGreaterThan(0);
    }
  });

  it('finds a known entry by id', () => {
    const entry = findRemoteDatasetEntry('lsg');
    if (entry) {
      expect(entry.id).toBe('lsg');
      expect(typeof entry.checksum).toBe('string');
      expect(typeof entry.sizeBytes).toBe('number');
    } else {
      // The catalogue is generated by scripts/bible/build-bible.ts — if it is
      // not present in this build context, assert the lookup degrades to null.
      expect(entry).toBeNull();
    }
  });

  it('returns null for an id not in the catalogue', () => {
    expect(findRemoteDatasetEntry('__does-not-exist__')).toBeNull();
  });
});
